/** 偏能照着做，体态/饮食多一些。不要鸡汤腔。 */
export const BUILTIN_QUOTES = [
  '带的饭已经算一顿，零食是第二顿。',
  '久坐不是休息，是肩往前掉。',
  '渴了先喝水。奶茶不是水。',
  '起来走一圈，比在椅子上继续坐着更有用。',
  '晚饭停早一点，十点半才睡得着。',
  '腹式呼吸不占地方，工位就能做。',
  '额外的一口，也会额外长在脸上。',
  '拉伸是今天的事，不是周末再补。',
  '低头看手机的那一小时，脖子会记着。',
  '喝够了再忙。忙不是不喝水的理由。',
  '运动不必很长，但今晚要发生。',
  '休息日可以加量，别练到周一站不直。',
  '坐直。肩往开，不要往桌子上送。',
  '甜饮料和零食走同一条路。',
  '走一走。现在。',
  '出门前防晒，不是等阳光提醒你。',
  '手和脖子也要抹。脸不是唯一晒得到的地方。',
  '中午补一次，比早上涂厚更有用。',
  '护肤认真，是把步骤做完，不是产品堆多。',
  '洁面做完再谈后面的。',
  '洗头也是护理。敷衍洗，发质会还回来。',
  '头发长了就去剪，别等有空。',
  '十点半是睡觉，不是躺着看屏幕。',
  '变好看是重复，不是某一天特别努力。',
]

export function quoteFor(dateKey: string, extra: string[]): string {
  const pool = extra.length > 0 ? [...BUILTIN_QUOTES, ...extra] : BUILTIN_QUOTES
  let n = 0
  for (let i = 0; i < dateKey.length; i++) n = (n * 31 + dateKey.charCodeAt(i)) | 0
  const index = Math.abs(n) % pool.length
  return pool[index]
}
